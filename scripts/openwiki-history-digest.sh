#!/usr/bin/env bash
# Write a bounded git-history digest for an OpenWiki update run.
#
# OpenWiki's agent cannot read git history here: while .openwikiignore has
# active rules, openwiki 0.3.2 restricts shell execute to `pwd`,
# `git rev-parse HEAD`, and deleting openwiki/_plan.md
# (dist/agent/docs-only-backend.js). This writes the history the update prompt
# expects into a file the agent can open with read_file.
set -euo pipefail

out=${1:-.openwiki-history.md}
max_commits=${OPENWIKI_HISTORY_MAX_COMMITS:-400}
max_files=${OPENWIKI_HISTORY_MAX_FILES:-400}
metadata=openwiki/.last-update.json

head_sha=$(git rev-parse HEAD)

base=""
if [ -f "$metadata" ]; then
  base=$(jq -r '.gitHead // empty' "$metadata" 2>/dev/null || true)
fi
if [ -n "$base" ] && ! git cat-file -e "${base}^{commit}" 2>/dev/null; then
  base=""
fi

{
  echo "# Change evidence since the last wiki update"
  echo
  echo "Generated by scripts/openwiki-history-digest.sh."
  echo "Current commit: ${head_sha}"
  echo
} >"$out"

if [ -z "$base" ]; then
  {
    echo "No reachable baseline commit is recorded in ${metadata}, so no change"
    echo "list is available. Compare current source and tests against the existing"
    echo "wiki instead, and do not guess at what changed."
  } >>"$out"
  echo "wrote ${out} (no baseline)"
  exit 0
fi

# The wiki's own pages change on every run and say nothing about the source
# the wiki documents. The agent reads openwiki/ directly instead.
exclude_wiki=':(exclude)openwiki/'

commit_total=$(git rev-list --no-merges --count "${base}..HEAD")
file_total=$(git diff --name-status "${base}..HEAD" -- . "$exclude_wiki" | wc -l | tr -d ' ')

{
  echo "Baseline commit: ${base} (the commit the wiki currently documents)"
  echo "Range: ${base}..HEAD"
  echo "Scope: ${commit_total} non-merge commits, ${file_total} changed files"
  echo "The wiki's own pages under openwiki/ are excluded from the file list."
  echo
  echo "Patches are excluded on purpose. Use this to find what changed and why,"
  echo "then read the current source for what the code does now."
  echo
  echo "## Commits, newest first"
  echo
  echo '```'
  git log --no-merges --format='%h %ad %s' --date=short "${base}..HEAD" |
    sed -n "1,${max_commits}p"
  echo '```'
  if [ "$commit_total" -gt "$max_commits" ]; then
    echo
    echo "Truncated to the newest ${max_commits} of ${commit_total} commits."
    echo "Treat the omitted commits as unknown, not as unchanged."
  fi
  echo
  echo "## Changed files, net across the range"
  echo
  echo '```'
  git diff --name-status "${base}..HEAD" -- . "$exclude_wiki" |
    sed -n "1,${max_files}p"
  echo '```'
  if [ "$file_total" -gt "$max_files" ]; then
    echo
    echo "Truncated to ${max_files} of ${file_total} changed files."
  fi
} >>"$out"

echo "wrote ${out} (${commit_total} commits, ${file_total} files)"
